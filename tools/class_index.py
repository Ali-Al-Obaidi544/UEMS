#!/usr/bin/env python3
"""Regenerates docs/CLASS_INDEX.md: which class is in which source file (run from the project folder)."""
import re, os, glob
decl = re.compile(r'^(?:public\s+)?(?:(?:abstract|final|sealed)\s+)*(class|interface|enum|record)\s+(\w+)', re.M)
out = ["# Class index", "", "Generated by tools/class_index.py.", ""]
for base in ("src/main/java/uems", "src/test/java/uems"):
    for f in sorted(glob.glob(base + "/*.java")):
        t = open(f, encoding="utf-8").read()
        out.append("## " + os.path.basename(f) + " (" + str(t.count("\n")) + " lines)")
        for m in decl.finditer(t): out.append("- " + m.group(1) + " " + m.group(2) + " (line " + str(t[:m.start()].count("\n") + 1) + ")")
        out.append("")
open("docs/CLASS_INDEX.md", "w", encoding="utf-8").write("\n".join(out))
